function buildGroup(skill, fixtures, judges, prepareTail = '') {
  const groupManifests = {};
  for (const fixture of fixtures) {
    const dir = `skills/${skill}/evals/fixtures/repos/${fixture}`;
    const files = manifest(dir);
    groupManifests[fixture] = files;
    emit(`${dir}/prepare-eval.cjs`, `#!/usr/bin/env node\n// Generated by scripts/evals/build-outcome-judges.cjs.\n${preparation}\nprepareFixture(${JSON.stringify(fixture)}, ${JSON.stringify(files, null, 2)});\n${prepareTail}\n`);
  }
  for (const [name, settings] of Object.entries(judges)) {
    const selected = Object.fromEntries(settings.fixtures.map((fixture) => [fixture, groupManifests[fixture]]));
    const body = settings.customState ? settings.body : `checkFixture(${JSON.stringify(selected, null, 2)}, ${JSON.stringify(settings.replacements || {})}, ${JSON.stringify(settings.options || {})});\n${settings.body || ''}`;
    const support = settings.trace ? shared : stateChecks;
    emit(`skills/${skill}/evals/fixtures/scripts/${name}.sh`, `#!/bin/bash\n# Generated by scripts/evals/build-outcome-judges.cjs; edit the source builder/helper.\nset -euo pipefail\nnode <<'EVAL_JUDGE_NODE'\n${support}\n${body}\nEVAL_JUDGE_NODE\n`);
  }
}

