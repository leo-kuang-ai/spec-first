function emit(relative, content) {
  const file = path.join(root, relative);
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return;
  if (checkOnly) { console.error(`Eval bundle drift: ${relative}`); drift = true; return; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}
function manifest(dir) {
  const files = {};
  function walk(relative) {
    for (const entry of fs.readdirSync(path.join(root, dir, relative), { withFileTypes: true })) {
      if (entry.name === 'prepare-eval.cjs') continue;
      const name = path.posix.join(relative, entry.name);
      if (entry.isDirectory()) walk(name);
      else if (entry.isFile()) files[name] = crypto.createHash('sha256').update(fs.readFileSync(path.join(root, dir, name))).digest('hex');
      else throw new Error(`Non-regular fixture: ${name}`);
    }
  }
  walk('');
  return files;
}
